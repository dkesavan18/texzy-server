/**
 * Shared dropdown options. Each option set is a `category_types` row (code = UPPER_SNAKE) and
 * every value is a `categories` row of that type — there are no per-feature master tables.
 */
export type OptionValueSeed = {
  name: string;
  /** Stable UPPER_SNAKE code; derived from the name when omitted. */
  code?: string;
  /** COLOUR only — HEX without '#'. Never the sole identifier of a textile shade. */
  hex?: string;
  /** COLOUR only — display name of the parent (base) colour. */
  parent?: string;
};

export type OptionSetSeed = {
  code: string;
  values: (string | OptionValueSeed)[];
};

const colour = (name: string, hex?: string, parent?: string): OptionValueSeed => ({
  name,
  hex,
  parent,
});

